// Generates web/data.js: 197 countries, accepted alternate names and SVG map shapes.
// Run: npm install && node gen-data.js
const fs = require('fs');
const path = require('path');
const { normalize } = require('../web/match.js');

async function main() {
  const countries = require('world-countries');
  const topojson = require('topojson-client');
  const { geoNaturalEarth1, geoPath } = await import('d3-geo');
  const world = require('world-atlas/countries-110m.json');

  // UN members, the two UN observer states, plus Kosovo and Taiwan.
  const EXTRA = new Set(['VA', 'PS', 'XK', 'TW']);
  const picked = countries.filter(c => c.unMember || EXTRA.has(c.cca2));

  const ALIASES = {
    US: ['usa', 'us', 'america', 'united states of america', 'states'],
    GB: ['uk', 'britain', 'great britain', 'gb'],
    AE: ['uae', 'emirates'],
    CD: ['drc', 'dr congo', 'democratic republic of congo', 'congo kinshasa', 'zaire'],
    CG: ['republic of congo', 'congo republic', 'congo brazzaville'],
    CF: ['car', 'central africa'],
    CZ: ['czech republic', 'czech'],
    NL: ['holland', 'netherland'],
    MM: ['burma'],
    SZ: ['swaziland'],
    CI: ['ivory coast', 'cote divoire'],
    CV: ['cabo verde'],
    TL: ['east timor', 'timor'],
    MK: ['macedonia', 'fyrom'],
    TR: ['turkey', 'turkiye'],
    VA: ['vatican', 'holy see'],
    PS: ['palestinian territories', 'state of palestine'],
    BA: ['bosnia', 'herzegovina', 'bosnia herzegovina'],
    TT: ['trinidad', 'tobago'],
    AG: ['antigua', 'barbuda'],
    KN: ['saint kitts', 'nevis'],
    VC: ['saint vincent', 'grenadines'],
    ST: ['sao tome', 'principe'],
    PG: ['png', 'papua', 'new guinea'],
    GW: ['bissau'],
    KR: ['republic of korea', 'rok'],
    KP: ['dprk'],
    RU: ['russian federation'],
    LA: ['lao'],
    BN: ['brunei darussalam'],
    MH: ['marshall'],
    SB: ['solomons', 'solomon'],
    SA: ['saudi', 'ksa'],
    DO: ['dominican', 'dominican rep'],
    LK: ['ceylon'],
    IR: ['persia'],
    TH: ['siam'],
    NZ: ['nz', 'aotearoa'],
    ZA: ['rsa'],
    KG: ['kirgizstan', 'kyrgyz'],
    BY: ['belorussia', 'byelorussia'],
    MV: ['maldive'],
    VN: ['viet nam'],
    TW: ['chinese taipei', 'formosa'],
    CN: ['prc', 'peoples republic of china'],
    IQ: ['irak'],
    MZ: ['mozambik'],
    PH: ['philipines', 'phillipines'],
    SV: ['salvador'],
    UA: ['the ukraine'],
    BS: ['bahama'],
    GM: ['the gambia'],
    KW: ['koweit']
  };

  const CONTINENT = c => {
    if (c.region === 'Americas') return c.subregion === 'South America' ? 'South America' : 'North America';
    if (c.region === 'Antarctic') return 'Oceania';
    return c.region;
  };

  // Natural Earth 110m; Antarctica is cut so the map stays usable on a phone.
  const WIDTH = 1000;
  const land = topojson.feature(world, world.objects.countries).features.filter(f => f.properties.name !== 'Antarctica');
  const projection = geoNaturalEarth1().fitWidth(WIDTH, { type: 'FeatureCollection', features: land });
  const draw = geoPath(projection).digits(1);
  const height = Math.ceil(draw.bounds({ type: 'FeatureCollection', features: land })[1][1]);

  // Features without an ISO number in the map file.
  const BY_NAME = { Kosovo: 'XK', Somaliland: 'SO', 'N. Cyprus': 'CY' };
  const byNumber = new Map(picked.map(c => [c.ccn3, c.cca2]));
  const shapes = new Map();
  const background = [];
  land.forEach(f => {
    const code = byNumber.get(f.id) || BY_NAME[f.properties.name];
    const d = draw(f);
    if (code) shapes.set(code, (shapes.get(code) || '') + d);
    else background.push(d);
  });

  const owner = new Map();
  picked.forEach(c => owner.set(normalize(c.name.common), c.cca2));
  const clashes = [];
  const out = picked.map(c => {
    const names = new Set([c.name.official, ...(c.altSpellings || []).filter(s => s.length >= 4), ...(ALIASES[c.cca2] || [])]);
    const a = [];
    names.forEach(name => {
      if (!/^[\p{Script=Latin}\s'’.,&()-]+$/u.test(name)) return;
      const key = normalize(name);
      if (key === normalize(c.name.common)) return;
      if (owner.has(key) && owner.get(key) !== c.cca2) { clashes.push(`${name}: ${owner.get(key)} vs ${c.cca2}`); return; }
      owner.set(key, c.cca2);
      a.push(name);
    });
    const entry = { c: c.cca2, n: c.name.common, r: CONTINENT(c), f: c.flag, a };
    if (shapes.has(c.cca2)) entry.d = shapes.get(c.cca2);
    else entry.p = projection([c.latlng[1], c.latlng[0]]).map(v => Math.round(v * 10) / 10);
    return entry;
  }).sort((x, y) => x.n.localeCompare(y.n));

  const data = { w: WIDTH, h: height, bg: background.join(''), countries: out };
  const file = path.join(__dirname, '..', 'web', 'data.js');
  fs.writeFileSync(file, '// Generated by tools/gen-data.js. Do not edit by hand.\nwindow.COUNTRY_DATA=' + JSON.stringify(data) + ';\n');

  console.log('countries', out.length, 'with shape', out.filter(c => c.d).length, 'as dots', out.filter(c => c.p).length);
  console.log('map', WIDTH + 'x' + height, 'file KB', Math.round(fs.statSync(file).size / 1024));
  const regions = {};
  out.forEach(c => regions[c.r] = (regions[c.r] || 0) + 1);
  console.log(regions);
  console.log('dropped alias clashes:', clashes);
  console.log('names:', out.map(c => c.n).join(', '));
}
main();
